export function t(lang, key) {
  return translations[lang]?.[key] ?? translations.en[key] ?? key;
}

export function pick(lang, bilingual) {
  if (!bilingual) return "";
  if (typeof bilingual === "string") return bilingual;
  return bilingual[lang] ?? bilingual.en ?? "";
}
